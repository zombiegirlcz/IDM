#!/usr/bin/env bash
# install-shell.sh — hook the IDM-like downloader into the Linux desktop the
# same way real IDM hooks Windows Explorer.
#
# What it installs (all under $HOME / XDG dirs, never system-wide):
#   * a GUI launcher   (~/.local/share/applications/idm-download.desktop)
#   * a URL scheme handler for the real IDM schemes `idmdwnlmfv9:` and `idmreg:`
#     (~/.local/share/applications/idm-scheme.desktop) + xdg registration
#   * a wrapper that forwards the incoming URL (%u) to the engine
#   * file-manager context-menu actions (Nautilus script + Thunar uca)
#
# Usage:
#   ./install-shell.sh                     # install
#   IDM_DOWNLOADS_DIR=/x ./install-shell.sh
#   ./install-shell.sh --uninstall         # remove
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

DOWNLOADS_DIR="${IDM_DOWNLOADS_DIR:-$HOME/Downloads}"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"

APPS_DIR="$DATA_HOME/applications"
NATIVE_DIR="$DATA_HOME/idm-native"
NAUTILUS_DIR="$DATA_HOME/nautilus/scripts"
THUNAR_DIR="$CONFIG_HOME/Thunar"

GUI_DESKTOP="$APPS_DIR/idm-download.desktop"
SCHEME_DESKTOP="$APPS_DIR/idm-scheme.desktop"
WRAPPER="$NATIVE_DIR/idm-shell-wrapper.sh"
GUI_WRAPPER="$NATIVE_DIR/idm-gui-wrapper.sh"
NAUTILUS_SCRIPT="$NAUTILUS_DIR/Stahnout s IDM"
THUNAR_UCA="$THUNAR_DIR/uca.xml"

ENGINE_BIN="${IDM_ENGINE_BIN:-$REPO_DIR/engine/target/release/idm}"
STATE_DIR_DEFAULT="$DATA_HOME/idm-gui"

UNINSTALL=0
if [[ "${1:-}" == "--uninstall" ]]; then
  UNINSTALL=1
fi

if [[ "$UNINSTALL" == 1 ]]; then
  rm -f "$GUI_DESKTOP" "$SCHEME_DESKTOP" "$WRAPPER" "$GUI_WRAPPER" "$NAUTILUS_SCRIPT"
  [[ -f "$THUNAR_UCA" ]] && rm -f "$THUNAR_UCA"
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
  fi
  echo "removed shell integration"
  exit 0
fi

if [[ ! -x "$ENGINE_BIN" ]]; then
  echo "warning: engine binary not executable: $ENGINE_BIN" >&2
  echo "         build it first: (cd '$REPO_DIR/engine' && cargo build --release)" >&2
fi

mkdir -p "$APPS_DIR" "$NATIVE_DIR" "$NAUTILUS_DIR" "$THUNAR_DIR" "$DOWNLOADS_DIR" "$STATE_DIR_DEFAULT"

# --- wrapper that receives the URL as %u and hands it to the engine ---------
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by install-shell.sh — do not edit.
# Receives an idmdwnlmfv9:// / idmreg: URL from the desktop and downloads it.
exec "$ENGINE_BIN" --output-dir "$DOWNLOADS_DIR" "\$@"
EOF
chmod +x "$WRAPPER"

# --- wrapper that opens the NATIVE GUI window ------------------------------
# The window is gui/idm_gui.py (Tkinter). It starts its own `idm --serve`
# backend via --autostart and talks to it over the local API. Falls back to a
# clear error if python3 is missing.
GUI_PY="$REPO_DIR/gui/idm_gui.py"
cat > "$GUI_WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by install-shell.sh — do not edit.
# Native window (Tkinter) with its own download backend.
exec "\${IDM_PYTHON:-python3}" "$GUI_PY" \
    --addr 127.0.0.1:8080 \
    --engine "$ENGINE_BIN" \
    --out-dir "$DOWNLOADS_DIR" \
    --state-dir "$STATE_DIR_DEFAULT" \
    --autostart
EOF
chmod +x "$GUI_WRAPPER"

# --- GUI launcher ----------------------------------------------------------
cat > "$GUI_DESKTOP" <<EOF
[Desktop Entry]
Type=Application
Name=IDM — správce stahování
Comment=Stahovat soubory a videa (multi-connection, resume)
Exec=$GUI_WRAPPER
Terminal=false
Categories=Network;FileTransfer;
Keywords=download;idm;stahovani;
EOF

# --- URL scheme handler (real IDM schemes) ---------------------------------
cat > "$SCHEME_DESKTOP" <<EOF
[Desktop Entry]
Type=Application
Name=IDM URL Handler
Comment=Handle idmdwnlmfv9:// and idmreg: download links
Exec=$WRAPPER %u
NoDisplay=true
MimeType=x-scheme-handler/idmdwnlmfv9;x-scheme-handler/idmreg;
EOF

# --- register the scheme with xdg ------------------------------------------
if command -v xdg-mime >/dev/null 2>&1; then
  xdg-mime default idm-scheme.desktop x-scheme-handler/idmdwnlmfv9 || true
  xdg-mime default idm-scheme.desktop x-scheme-handler/idmreg || true
fi

# Belt-and-braces: write mimeapps.list ourselves in case xdg-mime is a no-op.
MIMEAPPS="$CONFIG_HOME/mimeapps.list"
mkdir -p "$(dirname "$MIMEAPPS")"
{
  echo "[Default Applications]"
  echo "x-scheme-handler/idmdwnlmfv9=idm-scheme.desktop"
  echo "x-scheme-handler/idmreg=idm-scheme.desktop"
} >> "$MIMEAPPS"

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
fi

# --- file-manager context menu: Nautilus -----------------------------------
cat > "$NAUTILUS_SCRIPT" <<'EOF'
#!/usr/bin/env bash
# Nautilus script: "Stáhnout s IDM"
# Wraps each selected file as idmdwnlmfv9://file://... and hands it to IDM.
ENGINE="${IDM_ENGINE_BIN:-/root/IDM/engine/target/release/idm}"
for f in "$@"; do
  "$ENGINE" "idmdwnlmfv9://file://$f" &
done
EOF
chmod +x "$NAUTILUS_SCRIPT"

# --- file-manager context menu: Thunar -------------------------------------
cat > "$THUNAR_UCA" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<actions>
  <action>
    <icon>download</icon>
    <name>Stáhnout s IDM</name>
    <unique-id>idm-download-action</unique-id>
    <command>$WRAPPER idmdwnlmfv9://%f</command>
    <description>Download the selected file with IDM</description>
    <patterns>*</patterns>
    <directories/>
    <audio-files/>
    <image-files/>
    <other-files/>
    <text-files/>
    <video-files/>
  </action>
</actions>
EOF

echo "IDM shell integration installed"
echo "  GUI launcher : $GUI_DESKTOP"
echo "  scheme       : $SCHEME_DESKTOP (idmdwnlmfv9, idmreg)"
echo "  wrapper      : $WRAPPER"
echo "  downloads    : $DOWNLOADS_DIR"