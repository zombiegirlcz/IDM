#!/usr/bin/env bash
# install-host.sh — register the idm native-messaging host with Chromium-family
# browsers AND Firefox on Linux.
#
# The two families disagree about everything except the wire protocol: Chromium
# reads $HOME/.config/<browser>/NativeMessagingHosts and allows a
# chrome-extension:// origin, Firefox reads $HOME/.mozilla/native-messaging-hosts
# and allows an add-on id. Hence two manifest templates, one wrapper.
#
# The host (`idm-host`) REQUIRES --allowed-dir (fail-closed): without it it
# exits non-zero and writes nothing. Chrome spawns the host with no arguments,
# so we generate a small wrapper that supplies --allowed-dir (and --engine) and
# point the installed manifest's `path` at that wrapper.
#
# Usage:
#   ./install-host.sh                              # install
#   IDM_DOWNLOADS_DIR=/x ./install-host.sh         # custom downloads dir
#   ./install-host.sh --uninstall                  # remove
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOST_NAME="com.tonec.idm"
TEMPLATE_MANIFEST="$SCRIPT_DIR/$HOST_NAME.json"
FF_TEMPLATE_MANIFEST="$SCRIPT_DIR/$HOST_NAME.firefox.json"

DOWNLOADS_DIR="${IDM_DOWNLOADS_DIR:-$HOME/Downloads}"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
# Where the generated wrapper and the installed manifests live. install.sh
# points this inside $IDM_DIR so one directory holds the whole install; run on
# its own (a dev checkout) it keeps the historical XDG location.
STATE_DIR="${IDM_NATIVE_DIR:-$DATA_HOME/idm-native}"
# settings.json lives in the GUI's own state dir — the one install.sh passes to
# idm_gui.py as --state-dir. The host reads it for `get_settings`, which is the
# only way the extension learns about the File Types / key settings. Keep the
# two in step: change one and the extension silently falls back to defaults.
GUI_STATE_DIR="${IDM_STATE_DIR:-$DATA_HOME/idm-gui}"
SETTINGS_FILE="$GUI_STATE_DIR/settings.json"
WRAPPER="$STATE_DIR/idm-host-wrapper.sh"
INSTALLED_MANIFEST="$STATE_DIR/$HOST_NAME.json"
FF_INSTALLED_MANIFEST="$STATE_DIR/$HOST_NAME.firefox.json"

BROWSER_DIRS=(
  "$HOME/.config/google-chrome/NativeMessagingHosts"
  "$HOME/.config/chromium/NativeMessagingHosts"
  "$HOME/.config/microsoft-edge/NativeMessagingHosts"
  "$HOME/.config/BraveSoftware/Brave-Browser/NativeMessagingHosts"
)

# Firefox and its forks. Unlike Chromium's, these live directly under HOME.
FIREFOX_DIRS=(
  "$HOME/.mozilla/native-messaging-hosts"
  "$HOME/.librewolf/native-messaging-hosts"
)

for tpl in "$TEMPLATE_MANIFEST" "$FF_TEMPLATE_MANIFEST"; do
  if [[ ! -f "$tpl" ]]; then
    echo "error: missing host manifest template: $tpl" >&2
    exit 1
  fi
done

UNINSTALL=0
if [[ "${1:-}" == "--uninstall" ]]; then
  UNINSTALL=1
fi

if [[ "$UNINSTALL" == 1 ]]; then
  for dir in "${BROWSER_DIRS[@]}" "${FIREFOX_DIRS[@]}"; do
    target="$dir/$HOST_NAME.json"
    if [[ -L "$target" || -f "$target" ]]; then
      rm -f "$target"
      echo "removed  $target"
    fi
  done
  rm -f "$INSTALLED_MANIFEST" "$FF_INSTALLED_MANIFEST" "$WRAPPER"
  echo "removed  $INSTALLED_MANIFEST"
  echo "removed  $FF_INSTALLED_MANIFEST"
  exit 0
fi

# Real host binary + engine path from the template manifest.
HOST_BIN="$(python3 - "$TEMPLATE_MANIFEST" <<'PY'
import json,sys
print(json.load(open(sys.argv[1]))["path"])
PY
)"
ENGINE_BIN="$(dirname "$HOST_BIN")/idm"
if [[ ! -x "$HOST_BIN" ]]; then
  echo "warning: host binary not executable: $HOST_BIN" >&2
  echo "         build it first: (cd '$SCRIPT_DIR/../engine' && cargo build --release)" >&2
fi

mkdir -p "$STATE_DIR" "$DOWNLOADS_DIR"

# Wrapper: Chrome calls it with no args; it supplies the mandatory --allowed-dir.
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by install-host.sh — do not edit.
exec "$HOST_BIN" --engine "$ENGINE_BIN" --allowed-dir "$DOWNLOADS_DIR" --settings "$SETTINGS_FILE" "\$@"
EOF
chmod +x "$WRAPPER"

# Installed manifests point at the wrapper; the allowed_* keys come from each
# family's own template, so neither browser is handed a key it cannot read.
for pair in "$TEMPLATE_MANIFEST:$INSTALLED_MANIFEST" \
            "$FF_TEMPLATE_MANIFEST:$FF_INSTALLED_MANIFEST"; do
python3 - "${pair%%:*}" "${pair##*:}" "$WRAPPER" <<'PY'
import json,sys
src,dst,path=sys.argv[1],sys.argv[2],sys.argv[3]
m=json.load(open(src))
m["path"]=path
json.dump(m,open(dst,"w"),indent=2)
open(dst,"a").write("\n")
PY
done

for dir in "${BROWSER_DIRS[@]}"; do
  root="$(dirname "$(dirname "$dir")")"
  if [[ ! -d "$root" ]]; then
    continue
  fi
  mkdir -p "$dir"
  ln -sfn "$INSTALLED_MANIFEST" "$dir/$HOST_NAME.json"
  echo "linked   $dir/$HOST_NAME.json -> $INSTALLED_MANIFEST"
done

# Firefox's directory sits one level under HOME, so "is this browser here at
# all" asks about the parent ($HOME/.mozilla), not the grandparent.
for dir in "${FIREFOX_DIRS[@]}"; do
  if [[ ! -d "$(dirname "$dir")" ]]; then
    continue
  fi
  mkdir -p "$dir"
  ln -sfn "$FF_INSTALLED_MANIFEST" "$dir/$HOST_NAME.json"
  echo "linked   $dir/$HOST_NAME.json -> $FF_INSTALLED_MANIFEST"
done

echo
echo "Host name    : $HOST_NAME"
echo "Wrapper      : $WRAPPER"
echo "Downloads    : $DOWNLOADS_DIR"
echo "Manifest     : $INSTALLED_MANIFEST"
echo "Extension ID : $(python3 - "$INSTALLED_MANIFEST" <<'PY'
import json,sys
print(json.load(open(sys.argv[1]))["allowed_origins"][0].replace("chrome-extension://","").rstrip("/"))
PY
)"
